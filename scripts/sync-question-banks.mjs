import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const sourceDir = path.join(rootDir, 'question-banks');
const frontendDir = path.join(rootDir, 'frontend', 'public', 'question-banks');
const backendDir = path.join(rootDir, 'backend-do', 'question-banks');
const backendGeneratedFile = path.join(rootDir, 'backend-do', 'src', 'generated', 'questionBanks.ts');

function isPlainObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

async function ensureDirectory(dirPath) {
  await fs.mkdir(dirPath, { recursive: true });
}

function validateQuestion(question, bankId, index) {
  if (!isPlainObject(question)) {
    throw new Error(`Question ${index + 1} in "${bankId}" must be an object.`);
  }
  if (typeof question.id !== 'string' || !question.id.trim()) {
    throw new Error(`Question ${index + 1} in "${bankId}" is missing a valid "id".`);
  }
  if (typeof question.prompt !== 'string' || !question.prompt.trim()) {
    throw new Error(`Question ${index + 1} in "${bankId}" is missing a valid "prompt".`);
  }
}

function validateBank(bank, filename) {
  if (!isPlainObject(bank)) {
    throw new Error(`Question bank file "${filename}" must contain a JSON object.`);
  }
  if (typeof bank.id !== 'string' || !bank.id.trim()) {
    throw new Error(`Question bank file "${filename}" is missing a valid "id".`);
  }
  const expectedFilename = `${bank.id}.json`;
  if (expectedFilename !== filename) {
    throw new Error(`Question bank "${bank.id}" must be stored as "${expectedFilename}".`);
  }
  if (typeof bank.name !== 'string' || !bank.name.trim()) {
    throw new Error(`Question bank "${bank.id}" is missing a valid "name".`);
  }
  if (!Number.isInteger(bank.version) || bank.version <= 0) {
    throw new Error(`Question bank "${bank.id}" must have a positive integer "version".`);
  }
  if (!Array.isArray(bank.questions) || bank.questions.length === 0) {
    throw new Error(`Question bank "${bank.id}" must contain at least one question.`);
  }

  const seenQuestionIds = new Set();
  bank.questions.forEach((question, index) => {
    validateQuestion(question, bank.id, index);
    if (seenQuestionIds.has(question.id)) {
      throw new Error(`Question bank "${bank.id}" contains duplicate question id "${question.id}".`);
    }
    seenQuestionIds.add(question.id);
  });
}

function sortBanks(left, right) {
  return left.name.localeCompare(right.name, 'en', { sensitivity: 'base' }) || left.id.localeCompare(right.id, 'en');
}

function createManifest(banks) {
  const defaultBankId = banks.some((bank) => bank.id === 'classic_v1') ? 'classic_v1' : banks[0]?.id;
  if (!defaultBankId) {
    throw new Error('At least one question bank is required.');
  }
  return {
    defaultBankId,
    banks: banks.map((bank) => ({
      id: bank.id,
      name: bank.name,
      version: bank.version,
      questionCount: bank.questions.length,
    })),
  };
}

function toPrettyJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

async function loadBanks() {
  const entries = await fs.readdir(sourceDir, { withFileTypes: true });
  const files = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.json') && entry.name !== 'manifest.json')
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right, 'en'));

  const banks = [];
  for (const filename of files) {
    const filePath = path.join(sourceDir, filename);
    const raw = await fs.readFile(filePath, 'utf8');
    const bank = JSON.parse(raw);
    validateBank(bank, filename);
    banks.push(bank);
  }

  banks.sort(sortBanks);
  return banks;
}

async function copyBankFiles(banks, dirPath) {
  await ensureDirectory(dirPath);
  await Promise.all(
    banks.map((bank) =>
      fs.writeFile(path.join(dirPath, `${bank.id}.json`), toPrettyJson(bank), 'utf8')
    )
  );
}

async function writeManifestFiles(manifest) {
  const manifestJson = toPrettyJson(manifest);
  await fs.writeFile(path.join(sourceDir, 'manifest.json'), manifestJson, 'utf8');
  await fs.writeFile(path.join(frontendDir, 'manifest.json'), manifestJson, 'utf8');
  await fs.writeFile(path.join(backendDir, 'manifest.json'), manifestJson, 'utf8');
}

async function writeBackendGeneratedModule(banks, manifest) {
  await ensureDirectory(path.dirname(backendGeneratedFile));
  const content = `/* auto-generated by scripts/sync-question-banks.mjs; do not edit manually. */
export interface GeneratedQuestionDefinition {
  id: string;
  prompt: string;
}

export interface GeneratedQuestionBankDefinition {
  id: string;
  name: string;
  version: number;
  questions: GeneratedQuestionDefinition[];
}

export interface GeneratedQuestionBankSummary {
  id: string;
  name: string;
  version: number;
  questionCount: number;
}

export const defaultQuestionBankId = ${JSON.stringify(manifest.defaultBankId)};

export const questionBanks: Record<string, GeneratedQuestionBankDefinition> = ${JSON.stringify(
    Object.fromEntries(banks.map((bank) => [bank.id, bank])),
    null,
    2
  )};

export const questionBankSummaries: GeneratedQuestionBankSummary[] = ${JSON.stringify(manifest.banks, null, 2)};
`;
  await fs.writeFile(backendGeneratedFile, `${content}\n`, 'utf8');
}

async function main() {
  await ensureDirectory(frontendDir);
  await ensureDirectory(backendDir);

  const banks = await loadBanks();
  const manifest = createManifest(banks);

  await Promise.all([copyBankFiles(banks, frontendDir), copyBankFiles(banks, backendDir)]);
  await writeManifestFiles(manifest);
  await writeBackendGeneratedModule(banks, manifest);

  console.log(`Synced ${banks.length} question bank(s): ${banks.map((bank) => bank.id).join(', ')}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
