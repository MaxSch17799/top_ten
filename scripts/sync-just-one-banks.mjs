import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { validateWordBank } from '../shared/wordBank.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.join(root, 'word-banks/just-one');
const destination = path.join(root, 'frontend/public/banks/just-one');
await mkdir(destination, { recursive: true });
const files = (await readdir(source)).filter(
  (f) => f.endsWith('.json') && !f.endsWith('.schema.json'),
);
const banks = [];
for (const file of files.sort()) {
  const bank = JSON.parse(await readFile(path.join(source, file), 'utf8'));
  validateWordBank(bank);
  if (banks.some((b) => b.id === bank.id))
    throw new Error(`Duplicate bank id: ${bank.id}`);
  banks.push(bank);
  await writeFile(
    path.join(destination, file),
    JSON.stringify(bank, null, 2) + '\n',
  );
}
const summaries = banks.map(({ cards, development, ...bank }) => ({
  ...bank,
  development: !!development,
  cardCount: cards.length,
}));
await writeFile(
  path.join(destination, 'manifest.json'),
  JSON.stringify({ banks: summaries }, null, 2) + '\n',
);
await mkdir(path.join(root, 'backend-do/src/generated'), { recursive: true });
await writeFile(
  path.join(root, 'backend-do/src/generated/justOneBanks.ts'),
  `// Generated by scripts/sync-just-one-banks.mjs. Do not edit.\nimport type { WordBank, BankSummary } from '../../../shared/justOne.js';\nexport const justOneBanks: Record<string, WordBank> = ${JSON.stringify(Object.fromEntries(banks.map((b) => [b.id, b])), null, 2)};\nexport const justOneBankSummaries: BankSummary[] = ${JSON.stringify(summaries, null, 2)};\n`,
);
console.log(`Synced ${banks.length} Just One word bank(s).`);

// Keep translations server-side, alongside the banks, without changing the card format.
const translationRows = (
  await readFile(path.join(source, 'language/en-de.tsv'), 'utf8')
).split(/\r?\n/);
const translations = { en: {}, de: {} };
const normalize = (value) =>
  value
    .normalize('NFKC')
    .toLowerCase()
    .replace(/ä/g, 'ae')
    .replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue')
    .replace(/ß/g, 'ss')
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .trim()
    .replace(/\s+/g, ' ')
    .replace(/[’‘]/g, "'")
    .replace(/[‐‑–]/g, '-');
for (const row of translationRows) {
  if (!row.trim() || row.startsWith('#')) continue;
  const columns = row.split('\t');
  if (columns.length !== 2 || columns.some((column) => !column.trim()))
    throw new Error(`Invalid translation row: ${row}`);
  const [en, de] = columns.map((column) =>
    column.split(';').map((word) => word.trim()),
  );
  for (const [language, originals, foreign] of [
    ['en', en, de],
    ['de', de, en],
  ]) {
    for (const word of originals) {
      const key = normalize(word);
      translations[language][key] = [
        ...new Set([...(translations[language][key] ?? []), ...foreign]),
      ];
    }
  }
}
for (const bank of banks.filter((b) =>
  /^just_one_(en|de)_classic_v1$/.test(b.id),
)) {
  const missing = bank.cards
    .flatMap((card) => card.words)
    .filter((word) => !translations[bank.language][normalize(word)]);
  if (missing.length)
    throw new Error(
      `Missing ${bank.language} translations: ${missing.join(', ')}`,
    );
}
await writeFile(
  path.join(root, 'backend-do/src/generated/justOneTranslations.ts'),
  `// Generated from word-banks/just-one/language/en-de.tsv.\nexport const clueTranslations: Record<string, Record<string, string[]>> = ${JSON.stringify(translations, null, 2)};\n`,
);
console.log(
  'Validated English/German translation coverage for all classic mystery words.',
);
