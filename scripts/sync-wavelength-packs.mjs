import { readdir, readFile, mkdir } from "node:fs/promises";
import { writeIfChanged } from './lib/write-if-changed.mjs';
import { fileURLToPath } from "node:url";
import { validateWavePack } from "../shared/wavePack.mjs";
const root = new URL("../", import.meta.url),
  dir = new URL("spectrum-packs/wavelength/", root);
const packs = [];
for (const file of (await readdir(dir))
  .filter((f) => f.endsWith(".json") && !f.endsWith(".schema.json"))
  .sort()) {
  const pack = validateWavePack(
    JSON.parse(await readFile(new URL(file, dir), "utf8")),
  );
  if (packs.some((p) => p.packId === pack.packId))
    throw new Error("Duplicate Wavelength pack ID");
  packs.push(pack);
}
if (!packs.length) throw new Error("No Wavelength packs installed");
const summaries = packs.map((p) => ({
  packId: p.packId,
  language: p.language,
  title: p.title,
  count: p.spectrums.length,
  development: !!p.development,
}));
const output = new URL("backend-do/src/generated/wavelengthPacks.ts", root);
await mkdir(new URL("./", output), { recursive: true });
await writeIfChanged(
  output,
  `// Generated by scripts/sync-wavelength-packs.mjs\nimport type { SpectrumPack, WavePackSummary } from '../../../shared/wavelength.js';\nexport const wavePacks: Record<string, SpectrumPack> = ${JSON.stringify(Object.fromEntries(packs.map((p) => [p.packId, p])), null, 2)};\nexport const wavePackSummaries: WavePackSummary[] = ${JSON.stringify(summaries, null, 2)};\n`,
);
console.log(
  `Validated ${packs.length} Wavelength packs (${packs.map((p) => p.spectrums.length).join("/")} spectrums): ${fileURLToPath(output)}`,
);
